import { readFileSync, writeFileSync } from "node:fs";

const fromRoot = (name) => new URL("../" + name, import.meta.url);
const read = (name) => readFileSync(fromRoot(name), "utf8");
const manifest = JSON.parse(read("manifest.json"));
const versions = JSON.parse(read("versions.json"));
const metadata = JSON.parse(read("package.json"));
const semver = /^\d+\.\d+\.\d+$/;

if (
  manifest.name !== "Bonfire" ||
  !manifest.author ||
  !semver.test(manifest.version) ||
  !semver.test(manifest.minAppVersion) ||
  manifest.version !== metadata.version ||
  versions[manifest.version] !== manifest.minAppVersion
) {
  throw new Error("Theme version, minimum Obsidian version and project metadata must agree.");
}

const header = [
  "/* Bonfire " + manifest.version + " | Alan D. Darfin | MIT",
  " * Third-party licenses are in the licenses directory.",
  " * Generated by npm run build. Edit src/ to change the theme.",
  " */",
].join("\n");
const embeddedFonts = [
  ["Schoolbell", "Schoolbell-Regular.ttf"],
  ["Coming Soon", "ComingSoon-Regular.ttf"],
  ["Copse", "Copse-Regular.ttf"],
].map(([family, file]) => {
  const font = readFileSync(fromRoot("vendor/" + file)).toString("base64");
  return [
    "@font-face {",
    "  font-family: " + JSON.stringify(family) + ";",
    "  font-style: normal;",
    "  font-weight: 400;",
    "  font-display: swap;",
    '  src: url("data:font/ttf;base64,' + font + '") format("truetype");',
    "}",
  ].join("\n");
}).join("\n\n");
const versionLabel = "body { --bonfire-version-label: " + JSON.stringify(manifest.name + " " + manifest.version) + "; }";
const licenseNames = [
  "LICENSE",
  "licenses/Schoolbell-Apache-2.0.txt",
  "licenses/Coming-Soon-Apache-2.0.txt",
  "licenses/Copse-OFL.txt",
];
const notices = "/*\n" +
  licenseNames.map((name) => name + "\n\n" + read(name).trim()).join("\n\n") +
  "\n*/";
const output = [header, versionLabel, embeddedFonts, read("src/bonfire.css"),
  read("src/mobile.css"), read("src/writing.css"), read("src/basic.css"), notices]
  .map((part) => part.trimEnd())
  .join("\n\n") + "\n";

if (/obsidian-prism-theme|\.pt-[\w-]+|prismStyleSettingsButton/i.test(output)) {
  throw new Error("An old theme dependency was included in Bonfire.");
}

if (process.argv.includes("--check")) {
  if (read("theme.css") !== output) {
    throw new Error("theme.css is stale. Run npm run build.");
  }
  console.log("Theme CSS and manifest are in sync.");
} else {
  writeFileSync(fromRoot("theme.css"), output);
  console.log("Built Bonfire " + manifest.version + ".");
}
